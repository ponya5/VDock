def test_loop_survives_tick_errors(monkeypatch):
    calls = []
    stop_event = threading.Event()

    def boom():
        calls.append(1)
        if len(calls) >= 2:
            stop_event.set()
        raise RuntimeError('tick exploded')

    monkeypatch.setattr(triggers, '_tick', boom)
    triggers._loop(stop_event, 0)
    assert len(calls) == 2


