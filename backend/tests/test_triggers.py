def test_execute_action_runs_through_executor(store, emitted, monkeypatch):
    calls = []

    class FakeExecutor:
        def execute_action(self, action):
            calls.append(action)
            return ActionResult(True, 'did it')

    monkeypatch.setattr(triggers, '_executor', FakeExecutor())
    triggers.add_trigger({
        'event': {'type': 'webhook', 'key': 'launch'},
        'action': {'type': 'execute_action',
                   'action': {'type': 'url', 'config': {'url': 'http://x'}}},
    })
    assert triggers.fire_webhook_key('launch') == 1
    assert calls == [{'type': 'url', 'config': {'url': 'http://x'}}]
    fired = _fired(emitted)
    assert fired[0]['ok'] is True and fired[0]['detail'] == 'did it'


def test_throwing_executor_degrades_to_ok_false(store, emitted, monkeypatch):
    class Boom:
        def execute_action(self, action):
            raise RuntimeError('nope')

    monkeypatch.setattr(triggers, '_executor', Boom())
    trigger = triggers.add_trigger({
        'event': {'type': 'webhook', 'key': 'boom'},
        'action': {'type': 'execute_action', 'action': {'type': 'url'}},
    })
    triggers.fire_webhook_key('boom')
    fired = _fired(emitted)
    assert len(fired) == 1
    assert fired[0]['ok'] is False and 'nope' in fired[0]['detail']
    assert fired[0]['id'] == trigger['id']
    # And the loop is unharmed — a manual tick still works.
    triggers._tick(MONDAY)


