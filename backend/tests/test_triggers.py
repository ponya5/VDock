def _fired(events):
    return [p for n, p in events if n == 'trigger_fired']


def _notify_trigger(**over):
    body = {
        'event': {'type': 'time', 'at': '07:30'},
        'action': {'type': 'show_notification', 'title': 'Hi', 'message': 'm'},
    }
    body.update(over)
    return body


