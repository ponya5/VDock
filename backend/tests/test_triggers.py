def test_master_switch_pauses_engine_and_webhooks(store, emitted):
    tid = triggers.add_trigger(_notify_trigger())['id']
    triggers.add_trigger({
        'event': {'type': 'webhook', 'key': 'k'},
        'action': {'type': 'show_notification', 'title': 'w', 'message': 'm'},
    })
    assert triggers.is_enabled() is True

    triggers.set_enabled(False)
    triggers._tick(MONDAY)
    assert triggers.fire_webhook_key('k') == 0
    assert _fired(emitted) == []

    # Manual test-fire still works — the panel's smoke test stays honest.
    ok, _detail = triggers.fire_trigger(tid)
    assert ok is True
    assert len(_fired(emitted)) == 1


def test_master_switch_persists_with_the_store(store):
    triggers.set_enabled(False)
    on_disk = json.loads((store / 'triggers.json').read_text(encoding='utf-8'))
    assert on_disk['enabled'] is False
    triggers.reset()  # drop memory — reload must pick the flag back up
    assert triggers.is_enabled() is False


def test_resume_rebaselines_edges(store, emitted, monkeypatch):
    """A condition that came true while paused must not fire on resume."""
    snapshot = [{}]
    monkeypatch.setattr(agent_state, 'snapshot', lambda: snapshot[0])
    triggers.add_trigger({
        'event': {'type': 'agent_state', 'source': 'claude',
                  'state': 'permission'},
        'action': {'type': 'show_notification', 'title': 'a', 'message': 'm'},
    })
    triggers._tick()                       # baseline: no state yet
    triggers.set_enabled(False)
    snapshot[0] = {'claude': {'state': 'permission'}}
    triggers._tick()                       # paused — nothing
    triggers.set_enabled(True)             # re-baseline on resume
    triggers._tick()                       # first obs after resume = baseline
    assert _fired(emitted) == []


