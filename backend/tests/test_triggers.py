def test_time_trigger_fires_once_per_matching_minute(store, emitted):
    triggers.add_trigger(_notify_trigger())
    triggers._tick(MONDAY)
    triggers._tick(MONDAY.replace(second=45))
    assert len(_fired(emitted)) == 1
    # A different minute with a non-matching at fires nothing.
    triggers._tick(MONDAY.replace(minute=31))
    assert len(_fired(emitted)) == 1
    # Same minute the next day is a fresh edge.
    triggers._tick(TUESDAY)
    assert len(_fired(emitted)) == 2


